async def seed_scenarios(db: AsyncSession) -> int:
    """Insert seed scenarios if they don't exist. Returns count of inserted."""
    inserted = 0
    for data in SCENARIOS:
        existing = await db.execute(
            select(TrainingScenario).where(TrainingScenario.title == data["title"])
        )
        if existing.scalar_one_or_none():
            continue

        scenario = TrainingScenario(
            id=uuid.uuid4(),
            title=data["title"],
            description=data["description"],
            type=data["type"],
            difficulty=data["difficulty"],
            client_persona=data["client_persona"],
            system_prompt=data["system_prompt"],
            ideal_script=data["ideal_script"],
            success_criteria=data["success_criteria"],
            is_public=True,
            tags=data["tags"],
        )
        db.add(scenario)
        inserted += 1

    if inserted:
        await db.commit()
    return inserted


async def main() -> None:
    """Standalone entry point for seeding."""
    from app.core.database import async_session_factory

    async with async_session_factory() as db:
        count = await seed_scenarios(db)
        print(f"Inserted {count} training scenarios.")


if __name__ == "__main__":
    asyncio.run(main())
